-- 1. ÜRÜNLER TABLOSU
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  title text not null,
  category text not null,
  condition text,
  stock text,
  description text,
  image text
);

-- 2. GÜVENLİK (ROW LEVEL SECURITY - RLS) İZİNLERİ
alter table public.products enable row level security;

-- Ziyaretçiler ürünleri listeleyebilsin
drop policy if exists "Public Read Products" on public.products;
create policy "Public Read Products"
  on public.products for select
  using (true);

-- Admin panelinden ürün eklenebilsin
drop policy if exists "Public Insert Products" on public.products;
create policy "Public Insert Products"
  on public.products for insert
  with check (true);

-- Admin panelinden ürün güncellenebilsin
drop policy if exists "Public Update Products" on public.products;
create policy "Public Update Products"
  on public.products for update
  using (true);

-- Admin panelinden ürün silinebilsin
drop policy if exists "Public Delete Products" on public.products;
create policy "Public Delete Products"
  on public.products for delete
  using (true);

-- 3. FOTOĞRAF DEPOSU (STORAGE BUCKET: product-images)
insert into storage.buckets (id, name, public)
values ('product-images', 'product-images', true)
on conflict (id) do update set public = true;

-- Fotoğrafların herkes tarafından görüntülenebilmesi için izin
drop policy if exists "Public Read Images" on storage.objects;
create policy "Public Read Images"
  on storage.objects for select
  using (bucket_id = 'product-images');

-- Mobilden fotoğraf yüklenebilmesi için izin
drop policy if exists "Public Upload Images" on storage.objects;
create policy "Public Upload Images"
  on storage.objects for insert
  with check (bucket_id = 'product-images');

-- Fotoğraf silinebilmesi için izin
drop policy if exists "Public Delete Images" on storage.objects;
create policy "Public Delete Images"
  on storage.objects for delete
  using (bucket_id = 'product-images');

-- =========================================================================
-- 4. ZİYARETÇİ VE HAREKET ANALİTİĞİ TABLOSU (İSTEĞE BAĞLI / ÖNERİLEN)
-- Ziyaretçi sayısı, nereden girildiği ve hangi ürüne tıklandığını kaydeder.
-- =========================================================================
create table if not exists public.site_analytics (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  visitor_id text,
  event_type text,
  source text,
  device text,
  path text,
  product_id text,
  product_title text,
  action text,
  details text
);

alter table public.site_analytics enable row level security;

-- Herkes istatistik event'i ekleyebilsin (ziyaret kaydı için)
drop policy if exists "Public Insert Analytics" on public.site_analytics;
create policy "Public Insert Analytics"
  on public.site_analytics for insert
  with check (true);

-- Admin panelinden okunabilsin
drop policy if exists "Public Read Analytics" on public.site_analytics;
create policy "Public Read Analytics"
  on public.site_analytics for select
  using (true);

-- =========================================================================
-- 5. YÖNETİCİ ŞİFRESİ VE AYARLAR TABLOSU (admin_settings)
-- Admin paneli giriş şifresinin Supabase bulutta saklanması için gereklidir.
-- =========================================================================
create table if not exists public.admin_settings (
  key text primary key,
  value text not null,
  updated_at timestamp with time zone default timezone('utc'::text, now())
);

alter table public.admin_settings enable row level security;

-- Admin şifresini okuma politikası
drop policy if exists "Public Read Admin Settings" on public.admin_settings;
create policy "Public Read Admin Settings"
  on public.admin_settings for select
  using (true);

-- Admin şifresini ekleme politikası
drop policy if exists "Public Insert Admin Settings" on public.admin_settings;
create policy "Public Insert Admin Settings"
  on public.admin_settings for insert
  with check (true);

-- Admin şifresini güncelleme politikası
drop policy if exists "Public Update Admin Settings" on public.admin_settings;
create policy "Public Update Admin Settings"
  on public.admin_settings for update
  using (true);

